// 違反の一覧を返す。空配列なら合格。
export function check(text, { emergency = false } = {}) {
  const v = [];
  for (const { re, label } of [...FORBIDDEN, ...GUARANTEE]) {
    if (re.test(text)) v.push(label);
  }
  if (emergency && /[？?]/.test(text)) v.push('緊急時に問い返しをしている');
  return v;
}

// 違反ではないが記録しておく項目（問い返しは「1回答につき1つまで」）
export function warnings(text, { emergency = false } = {}) {
  const w = [];
  if (!emergency && (text.match(/[？?]/g) || []).length >= 3) {
    w.push('「？」が3つ以上（問い返しの数を要確認）');
  }
  return w;
}
