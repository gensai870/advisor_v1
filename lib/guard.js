// 出力検査（編集メモ v4.1 §3-4 の要修正表現、基本指示 v4.1 §5 のルールに対応）

export const FORBIDDEN = [
  { re: /正解は被害が決/, label: '「正解は被害が決める」（原理は「答えは問題で決まる」に一本化）' },
  { re: /提唱/, label: '「提唱」（「協会が考える／取り組む」と表現）' },
  { re: /現場実践|現場研修/, label: '旧称「現場実践／現場研修」（正式名称は実装研修）' },
  { re: /月額\s*9,?000\s*円|実証\s*3\s*施設/, label: '出どころ未確認の料金・実績' },
];

export const GUARANTEE = [
  { re: /(絶対|必ず|完全)に?安全(です|だ|になります|に守れ)/, label: '安全の保証表現' },
  { re: /安全(を|が)保証(します|されます)/, label: '安全の保証表現' },
];

// 用語の統一（残存リスク → 残留リスク）。違反扱いにせず機械的に置換する。
export function normalize(text) {
  return text.replace(/残存リスク/g, '残留リスク');
}

// 今まさに災害が起きている発話の検知（基本指示 v4.1 §5-2）
const EMERGENCY = new RegExp(
  [
    '揺れて(い)?る',
    'ゆれて(い)?る',
    '揺れが(続|止まらな|収まらな)',
    '地震が(来て|きて|起き(て|ました))',
    '津波が(来て|きて|迫って)',
    '今(まさに)?[、,\\s]*(地震|揺れ|津波|火事)(?!に|の|は|って|とは|について|が起きたら|が来たら)',
    '助けて',
  ].join('|'),
);

export function isEmergency(text) {
  return EMERGENCY.test(text || '');
}

